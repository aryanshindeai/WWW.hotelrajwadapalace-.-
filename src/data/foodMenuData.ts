/**
 * Returns the exact count of items for a category tab
 */
export function getMenuCategoryCount(categoryId: MenuCategorySlug): number {
  if (categoryId === 'all') {
    return RESTAURANT_MENU_ITEMS.length;
  }
  return RESTAURANT_MENU_ITEMS.filter((item) => item.category === categoryId).length;
}
